"""Replace the manuscript's generated tables and figures with those on disk.

The Overleaf bundle is self-contained: tables are inlined in main.tex rather
than \\input, and figures are copied into overleaf/figs/ rather than referenced
across the tree. That is the right choice for a bundle a co-author can compile,
and it means two copies of every generated artifact. Keeping those in step by
hand is what produces a paper whose table says one thing and whose figure,
drawn from the same store, says another -- the failure mode hardest to spot,
because nothing is broken, the digits are merely old.

Tables are rewritten in place from tables/tex/tab_*.tex, matched on
\\label{tab:...}. Figures are copied from figs/ to overleaf/figs/, matched on
the \\includegraphics paths the manuscript actually cites -- so the set of
figures that belong in the bundle is derived from the manuscript rather than
maintained as a second list that can fall out of date.

Nothing else is touched: prose, captions, and the position of every float stay
where they are.

    python src/sync.py                  # report + rewrite
    python src/sync.py --check          # report only
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

from paths import TEX as GEN, FIG as FIGS, FIGURES, MAIN_TEX as MAIN  # noqa: E402

BUNDLE_FIGS = MAIN.parent / "figs"
MARK = "% generated by src/tables.py"
# Match any generator path, not just the current one: when the script is
# renamed, an exact match stops recognising the comment it wrote last time
# and leaves it stranded above the new one.
MARK_RE = re.compile(r"^% generated by \S+\.py$")

TABLES = {"tab_stability": "tab:stability", "tab_rmse": "tab:rmse",
          "tab_noise": "tab:noise", "tab_oracle": "tab:oracle"}


def span(tex, label):
    """The \\begin{table}...\\end{table} block carrying this label."""
    m = re.search(r"\\label\{" + re.escape(label) + r"\}", tex)
    if not m:
        return None
    start = tex.rfind(r"\begin{table}", 0, m.start())
    if start < 0:
        return None
    end = tex.find(r"\end{table}", m.end())
    if end < 0:
        return None
    end += len(r"\end{table}")
    # Swallow the provenance comment above the block so it is not duplicated.
    head = tex.rfind("\n", 0, start - 1) + 1
    if MARK_RE.match(tex[head:start].strip() or "x"):
        start = head
    return start, end


def cited_figures(tex):
    """Basenames of every figure the manuscript includes, in citation order.

    Deriving the list from \\includegraphics means a figure that is dropped
    from the paper stops being synced the moment its \\includegraphics goes,
    and a newly cited one starts being synced without anyone remembering to
    add it here.
    """
    seen, out = set(), []
    for m in re.finditer(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", tex):
        name = Path(m.group(1)).name
        if name not in seen:
            seen.add(name)
            out.append(name)
    return out


# Where a cited figure has to end up. figures/ is the tracked copy -- the
# answer to "which of the 90 PNGs does the paper actually use" -- and
# overleaf/figs/ is the bundle Overleaf compiles. Both are derived from the
# manuscript, so neither is a list anyone maintains.
DESTS = (FIGURES, BUNDLE_FIGS)


def sync_figures(tex, check):
    """Copy each cited figure from the generator output to every destination."""
    stale, absent = [], []
    for d in DESTS:
        d.mkdir(parents=True, exist_ok=True)
    for name in cited_figures(tex):
        src = FIGS / name
        if not src.exists():
            # A destination may still hold a usable copy; say so rather than
            # implying the manuscript is broken.
            have = (" (a copy is already in place)"
                    if all((d / name).exists() for d in DESTS) else " -- MISSING")
            absent.append(name)
            print(f"  {name:<46} not generated{have}")
            continue
        need = [d for d in DESTS
                if not (d / name).exists()
                or (d / name).read_bytes() != src.read_bytes()]
        if not need:
            print(f"  {name:<46} up to date")
            continue
        stale.append(name)
        where = ", ".join(d.name for d in need)
        print(f"  {name:<46} STALE" + ("" if check else f" -- copied to {where}"))
        if not check:
            for d in need:
                shutil.copy2(src, d / name)

    # Figures a destination carries that the manuscript no longer cites. These
    # are reported, never removed: a stray PNG costs nothing, whereas deleting
    # one that a co-author added to a branch of the manuscript costs work.
    cited = set(cited_figures(tex))
    for d in DESTS:
        for q in sorted(d.iterdir()):
            if q.is_file() and not q.name.startswith(".") and q.name not in cited:
                print(f"  {q.name:<46} in {d.name}/, not cited")
    return stale, absent


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="report differences and exit non-zero; change nothing")
    ap.add_argument("--main", default=str(MAIN))
    args = ap.parse_args()

    path = Path(args.main)
    if not path.exists():
        print(f"no manuscript at {path}")
        return 1
    tex = path.read_text()
    stale, missing = [], []

    print("tables")
    for name, label in TABLES.items():
        gen = GEN / f"{name}.tex"
        if not gen.exists():
            print(f"  {label:<14} no generated file -- run tables.py")
            continue
        sp = span(tex, label)
        if sp is None:
            missing.append(label)
            print(f"  {label:<14} not in the manuscript")
            continue
        new = MARK + "\n" + gen.read_text().rstrip()
        cur = tex[sp[0]:sp[1]]
        if cur.strip() == new.strip():
            print(f"  {label:<14} up to date")
            continue
        stale.append(label)
        print(f"  {label:<14} STALE"
              + ("" if args.check else " -- rewritten"))
        if not args.check:
            tex = tex[:sp[0]] + new + tex[sp[1]:]

    if not args.check and stale:
        path.write_text(tex)
        print(f"  rewrote {len(stale)} table(s) in {path}")

    print("\nfigures")
    fig_stale, fig_absent = sync_figures(tex, args.check)
    if not args.check and fig_stale:
        print(f"  copied {len(fig_stale)} figure(s) into "
              + " and ".join(str(d) for d in DESTS))

    print()
    if missing:
        print(f"{len(missing)} generated table(s) are not in the manuscript: "
              + ", ".join(missing))
    if args.check and (stale or fig_stale):
        print(f"{len(stale)} table(s) and {len(fig_stale)} figure(s) differ "
              f"from the generated output.")
        return 1
    # A cited figure with no generator output is reported but does not fail:
    # the bundle copy may be the only one on a machine that has not re-run the
    # 3D stage, and failing there would make the check unrunnable off the GPU box.
    if fig_absent:
        print(f"{len(fig_absent)} cited figure(s) have no generated source "
              f"here: " + ", ".join(fig_absent))
    return 0


if __name__ == "__main__":
    sys.exit(main())
